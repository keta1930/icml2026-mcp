"""从运行时 schema 生成 MCP 与配置 Reference 片段。"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "generated"
sys.path.insert(0, str(ROOT / "src"))

from icml_paper_search.config import Settings  # noqa: E402
from icml_paper_search.server import create_mcp  # noqa: E402


def _schema_type(schema: dict[str, Any]) -> str:
    """把 JSON Schema 类型压缩成适合表格的文本。"""
    if "anyOf" in schema:
        values = [_schema_type(value) for value in schema["anyOf"]]
        return " | ".join(dict.fromkeys(values))
    if schema.get("type") == "array":
        return f"{_schema_type(schema.get('items', {}))}[]"
    return str(schema.get("type", "any"))


def _constraints(schema: dict[str, Any]) -> str:
    """提取对调用者有意义的边界约束。"""
    target = next(
        (item for item in schema.get("anyOf", []) if item.get("type") != "null"),
        schema,
    )
    labels = {
        "minimum": "≥",
        "exclusiveMinimum": "＞",
        "maximum": "≤",
        "exclusiveMaximum": "＜",
        "minLength": "min chars",
        "maxLength": "max chars",
        "minItems": "min items",
        "maxItems": "max items",
    }
    return ", ".join(
        f"{label} {target[key]}" for key, label in labels.items() if key in target
    ) or "—"


def _default(value: Any) -> str:
    """渲染稳定、脱敏的默认值。"""
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return str(value).lower()
    if value == "":
        return '`""`'
    if isinstance(value, (list, tuple)):
        return f"`{json.dumps(value, ensure_ascii=False)}`"
    return f"`{value}`"


def _tool_reference() -> str:
    """从 FastMCP tool schema 生成参数表。"""
    server = create_mcp(Settings(_env_file=None))
    sections = ["{/* Generated by docs/scripts/generate_reference.py. */}"]
    for tool in server._tool_manager.list_tools():
        schema = tool.parameters
        required = set(schema.get("required", []))
        sections.extend(
            [
                "",
                f"### `{tool.name}`",
                "",
                tool.description or "—",
                "",
                "| 参数 | 类型 | 必填 | 默认值 | 约束 | 说明 |",
                "|---|---|---:|---|---|---|",
            ]
        )
        properties = schema.get("properties", {})
        if not properties:
            sections.append("| — | — | — | — | — | 无参数 |")
        for name, prop in properties.items():
            default = "—" if name in required else _default(prop.get("default"))
            description = str(prop.get("description", "—")).replace("|", "\\|")
            value_type = _schema_type(prop).replace("|", "\\|")
            sections.append(
                f"| `{name}` | `{value_type}` | "
                f"{'是' if name in required else '否'} | {default} | "
                f"{_constraints(prop)} | {description} |"
            )
        sections.extend(["", "返回：MCP text content；失败时返回稳定的 `error[code]` 文本。"])
    return "\n".join(sections) + "\n"


def _configuration_reference() -> str:
    """从 Settings JSON Schema 生成环境变量表。"""
    schema = Settings.model_json_schema()
    path_defaults = {
        "data_dir": "data",
        "index_root": ".data/index",
        "state_db_path": ".data/state/runtime.sqlite3",
    }
    lines = [
        "{/* Generated by docs/scripts/generate_reference.py. */}",
        "",
        "| 环境变量 | 类型 | 默认值 | 约束 |",
        "|---|---|---|---|",
    ]
    for name, prop in schema.get("properties", {}).items():
        env_name = f"ICML_PAPERS_{name.upper()}"
        value = path_defaults.get(name, prop.get("default"))
        if name in {"dashscope_api_key", "dashscope_api_key_file"}:
            value = None
        value_type = _schema_type(prop).replace("|", "\\|")
        lines.append(
            f"| `{env_name}` | `{value_type}` | {_default(value)} | "
            f"{_constraints(prop)} |"
        )
    return "\n".join(lines) + "\n"


def _write(path: Path, content: str, *, check: bool) -> bool:
    """写入变化内容，check 模式只报告漂移。"""
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return False
    if check:
        raise SystemExit(f"generated reference is stale: {path.relative_to(ROOT)}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def main() -> int:
    """生成或校验两个 Reference 片段。"""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = [
        _write(OUTPUT / "mcp-tools.mdx", _tool_reference(), check=args.check),
        _write(
            OUTPUT / "configuration.mdx",
            _configuration_reference(),
            check=args.check,
        ),
    ]
    if not args.check:
        print(f"generated reference files: {sum(changed)} changed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
